/**
 * FILE-BASED APP DISCOVERY — scans the repo-root `/apps/<name>/index.js`
 * convention (that directory's own `README.md` has the full "why here, not
 * Storage" reasoning) and writes a small, GENERATED, git-ignored static-
 * import file `admin-actions.js` imports from - `generatedAppsRegistry()`
 * is called from `build.mjs`'s `buildAppShellBundle()`, right before
 * esbuild runs, so both this package's own `relay-server.js` (at container
 * BOOT time) and `demo/app-shell-web/build.mjs` pick up whatever's in
 * `/apps` automatically, with zero code changes anywhere else needed to add
 * a new app.
 *
 * WHY A GENERATED FILE, NOT A RUNTIME `readdir()`: esbuild's `bundle: true`
 * mode resolves `import` statements at BUILD time - it has no equivalent of
 * Vite's `import.meta.glob()` to auto-discover a directory's files itself
 * (this project's own root `package.json` deliberately depends on esbuild,
 * not Vite - `build.mjs`'s own doc comment). A plain Node `readdir()` inside
 * the BROWSER bundle wouldn't work at all (no filesystem in a browser) -
 * so this scan has to happen ONE level up, in the build step itself,
 * producing a file esbuild can then bundle exactly like any other static
 * import.
 *
 * SAFE TO RE-RUN: overwrites the generated file every call - the only
 * state that matters (which `/apps/*` folders currently exist) is re-read
 * fresh each time, never accumulated/cached across builds.
 */
import { readdir, access, writeFile, mkdir } from 'node:fs/promises';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * @param {{appsDir: string, outFile: string}} params - `appsDir` the repo-root `/apps` directory; `outFile` where to write the generated registry (a `.js` file `build.mjs` then points esbuild at, indirectly, via whatever imports it - see `admin-actions.js`'s own import of this file's default output path).
 * @returns {Promise<{names: string[]}>} the app folder names actually included (for a one-line build log).
 */
export async function generateAppsRegistry({ appsDir, outFile }) {
  let entries = [];
  try {
    entries = await readdir(appsDir, { withFileTypes: true });
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
    entries = []; // no /apps directory at all yet - a correct "zero file-based apps" registry, not a build failure.
  }

  const names = [];
  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const indexPath = join(appsDir, entry.name, 'index.js');
    try {
      await access(indexPath);
      names.push(entry.name);
    } catch {
      console.warn(`[apps-registry] skipping /apps/${entry.name} - no index.js found.`);
    }
  }
  names.sort(); // deterministic output - never depend on the OS's own readdir() ordering.

  const outDir = dirname(outFile);
  const lines = [
    '// AUTO-GENERATED by apps-registry.mjs - DO NOT EDIT BY HAND. Regenerated on every build/boot.',
    ...names.map((name, i) => `import app${i} from '${relative(outDir, join(appsDir, name, 'index.js')).split('\\').join('/')}';`),
    `export const discoveredApps = [${names.map((_, i) => `app${i}`).join(', ')}];`,
    '',
  ].join('\n');

  await mkdir(outDir, { recursive: true });
  await writeFile(outFile, lines, 'utf8');
  return { names };
}

// COMMITTED, not git-ignored, unlike an ordinary build artifact (`dist/bundle.js`) - `admin-actions.js`
// imports it directly, and `node --test` runs against plain source, never through `build.mjs`/esbuild
// first - so a COMMITTED, possibly slightly stale copy is what tests (and anyone reading the source)
// see, not an always-fresh one. `buildAppShellBundle()` still regenerates it on every real bundle
// (container boot, `demo/app-shell-web` build), so a DEPLOYED relay is always current regardless -
// only local test runs need this CLI re-run by hand after adding/removing an `/apps/*` folder.
if (import.meta.url === `file://${process.argv[1]}`) {
  const here = dirname(fileURLToPath(import.meta.url));
  const { names } = await generateAppsRegistry({ appsDir: join(here, '..', '..', 'apps'), outFile: join(here, 'apps-registry.generated.js') });
  console.log(`[apps-registry] wrote apps-registry.generated.js (${names.length ? names.join(', ') : 'no apps found'})`);
}
